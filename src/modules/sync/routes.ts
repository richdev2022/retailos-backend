const ListSyncEventsQuerySchema = PaginationSchema.extend({
  status: SyncStatusEnum.optional(),
  operation: SyncOperationEnum.optional(),
  deviceId: z.string().max(200).optional(),
  from: z.string().datetime().optional(),
  to: z.string().datetime().optional(),
});

syncRouter.get(
  '/events',
  requirePermission('sale:view'),
  validateQuery(ListSyncEventsQuerySchema),
  asyncHandler(async (req: Request, res: Response) => {
    const bizId = req.activeBusinessId!;
    const q = req.query as unknown as z.infer<typeof ListSyncEventsQuerySchema>;

    const where: Prisma.SyncEventWhereInput = { businessId: bizId };
    if (q.status) where.status = q.status;
    if (q.operation) where.operation = q.operation;
    if (q.deviceId) where.deviceId = q.deviceId;
    if (q.from || q.to) {
      where.createdAt = {
        ...(q.from ? { gte: new Date(q.from) } : {}),
        ...(q.to ? { lte: new Date(q.to) } : {}),
      };
    }
    if (q.search) {
      where.OR = [
        { clientTxId: { contains: q.search } },
        { error: { contains: q.search } },
      ];
    }

    const total = await prisma.syncEvent.count({ where });
    const items = await prisma.syncEvent.findMany({
      ...paginate(
        { where, orderBy: { createdAt: 'desc' as const } },
        q,
      ),
      include: {
        user: { select: { id: true, fullName: true, email: true } },
      },
    });

    return sendSuccess(
      res,
      {
        items,
        meta: pageMeta(total, q),
      },
      'OK',
    );
  }),
);

