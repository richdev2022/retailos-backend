// POST /sync/push
// =====================================================
const SyncPushOperationSchema = z.object({
  clientTxId: z.string().min(1).max(200),
  operation: SyncOperationEnum,
  payload: z.record(z.any()),
  createdAt: z.string(),
});

const SyncPushSchema = z.object({
  deviceId: z.string().max(200).optional().nullable(),
  operations: z.array(SyncPushOperationSchema).min(1).max(500),
});

syncRouter.post(
  '/push',
  requirePermission('sale:process'), // sync push requires sale:process; ops inside additionally gated by replay validation
  validateBody(SyncPushSchema),
  asyncHandler(async (req: Request, res: Response) => {
    const bizId = req.activeBusinessId!;
    if (!req.user) return sendError(res, Errors.unauthorized());
    const body = req.body as z.infer<typeof SyncPushSchema>;
    const userId = req.user.id;
    const deviceId = body.deviceId ?? null;

    const results: SyncPushResultItem[] = [];

    for (const op of body.operations) {
      // 1. Idempotency — check existing SyncEvent.
      const existing = await prisma.syncEvent.findFirst({
        where: { businessId: bizId, clientTxId: op.clientTxId },
      });
      if (existing) {
        results.push({
          clientTxId: op.clientTxId,
          status: existing.status === 'PROCESSED' ? 'PROCESSED' : existing.status === 'REJECTED' ? 'REJECTED' : 'QUEUED',
          result: (existing.result as any) ?? null,
          error: existing.error ?? undefined,
        });
        continue;
      }

      // 2. Create SyncEvent as QUEUED. Catch concurrent insert → re-fetch.
      let syncEvent;
      try {
        syncEvent = await prisma.syncEvent.create({
          data: {
            businessId: bizId,
            userId,
            deviceId,
            operation: op.operation,
            clientTxId: op.clientTxId,
            status: 'QUEUED',
            payload: op.payload as any,
          },
        });
      } catch (err: any) {
        if (err?.code === 'P2002') {
          const concurrent = await prisma.syncEvent.findFirst({
            where: { businessId: bizId, clientTxId: op.clientTxId },
          });
          if (concurrent) {
            results.push({
              clientTxId: op.clientTxId,
              status:
                concurrent.status === 'PROCESSED'
                  ? 'PROCESSED'
                  : concurrent.status === 'REJECTED'
                    ? 'REJECTED'
                    : 'QUEUED',
              result: (concurrent.result as any) ?? null,
              error: concurrent.error ?? undefined,
            });
            continue;
          }
        }
        throw err;
      }

      // 3. Process inside a single tx — the SyncEvent is updated to PROCESSED
      //    atomically with the operation itself.
      try {
        const created = await prisma.$transaction(async (tx: Tx) => {
          const result = await replayOperation(tx, bizId, userId, op);
          await tx.syncEvent.update({
            where: { id: syncEvent.id },
            data: {
              status: 'PROCESSED',
              processedAt: new Date(),
              result: { id: result.id } as any,
            },
          });
          return result;
        });

        results.push({
          clientTxId: op.clientTxId,
          status: 'PROCESSED',
          result: { ...created, id: created.id },
        });
      } catch (err: any) {
        const msg = errorMessage(err).slice(0, 2000);
        // Update the QUEUED SyncEvent to REJECTED (best-effort).
        await prisma.syncEvent
          .update({
            where: { id: syncEvent.id },
            data: {
              status: 'REJECTED',
              error: msg,
              processedAt: new Date(),
            },
          })
          .catch(() => {
            /* never throw from cleanup */
          });

        // If it's an AppError, surface its code; otherwise generic.
        const code = err instanceof AppError ? err.code : 'SYNC_REJECTED';
        results.push({
          clientTxId: op.clientTxId,
          status: 'REJECTED',
          error: code === 'SYNC_REJECTED' ? msg : `${code}: ${msg}`,
        });
      }
    }

    writeAudit(req, {
      action: 'sync.push',
      resourceType: 'sync_event',
      resourceId: bizId,
      change: {
        deviceId,
        batchCount: body.operations.length,
        processed: results.filter((r) => r.status === 'PROCESSED').length,
        rejected: results.filter((r) => r.status === 'REJECTED').length,
      },
    });

    return sendSuccess(res, { results }, 'Sync batch processed');
  }),
);

