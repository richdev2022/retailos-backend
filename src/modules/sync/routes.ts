/**
 * Replay a sale. Mirrors POST /sales with syncId=clientTxId for idempotency.
 * Money arrives as decimal strings; converted to minor via toMinor.
 * Throws AppError on validation / stock failures.
 */
async function replaySale(
  tx: Tx,
  bizId: string,
  userId: string,
  clientTxId: string,
  payload: Record<string, unknown>,
): Promise<{ id: string; receiptNo: string }> {
  // Validate payload shape.
  const SaleItemSchema = z.object({
    productId: z.string().uuid(),
    quantity: z.number().int().min(1).max(1_000_000_000),
    unitPrice: moneyString.optional(),
    discount: moneyString.optional(),
  });
  const SalePaymentSchema = z.object({
    method: PaymentMethodEnum,
    amount: moneyString,
    reference: z.string().max(200).optional().nullable(),
  });
  const SaleSchema = z.object({
    items: z.array(SaleItemSchema).min(1),
    discount: moneyString.optional(),
    customerId: z.string().uuid().optional().nullable(),
    payments: z.array(SalePaymentSchema).default([]),
    branchId: z.string().uuid().optional().nullable(),
    notes: z.string().max(5000).optional().nullable(),
    saleDate: z.string().datetime().optional(),
  });

  const parsed = SaleSchema.safeParse(payload);
  if (!parsed.success) {
    throw Errors.badRequest(
      `Invalid sale payload: ${parsed.error.issues.map((i) => i.path.join('.') + ': ' + i.message).join('; ')}`,
      'SYNC_INVALID_PAYLOAD',
    );
  }
  const body = parsed.data;
  const branchId = body.branchId ?? null;

  // 1. Idempotency at the sale level (syncId=clientTxId).
  const existingSale = await tx.sale.findFirst({
    where: { businessId: bizId, syncId: clientTxId },
    select: { id: true, receiptNo: true },
  });
  if (existingSale) {
    return { id: existingSale.id, receiptNo: existingSale.receiptNo };
  }

  // 2. Validate products belong to the business.
  const productIds = Array.from(new Set(body.items.map((i) => i.productId)));
  const products = await tx.product.findMany({
    where: { id: { in: productIds }, businessId: bizId },
    select: { id: true, name: true, sku: true, sellingPriceMinor: true, status: true },
  });
  const productMap = new Map(products.map((p) => [p.id, p]));
  if (productMap.size !== productIds.length) {
    const missing = productIds.filter((id) => !productMap.has(id));
    throw Errors.badRequest(
      `Products not found: ${missing.join(', ')}`,
      'PRODUCT_NOT_FOUND',
    );
  }
  const inactive = products.filter((p) => p.status !== 'ACTIVE');
  if (inactive.length > 0) {
    throw Errors.badRequest(
      `Inactive products: ${inactive.map((p) => p.sku).join(', ')}`,
      'PRODUCT_INACTIVE',
    );
  }

  // 3. Resolve the business (for taxRateBps) and customer.
  const business = await tx.business.findUnique({
    where: { id: bizId },
    select: { id: true, taxRateBps: true, currency: true },
  });
  if (!business) throw Errors.notFound('Business not found');

  if (body.customerId) {
    const customer = await tx.customer.findFirst({
      where: { id: body.customerId, businessId: bizId },
      select: { id: true },
    });
    if (!customer) {
      throw Errors.badRequest('Customer not found', 'CUSTOMER_NOT_FOUND');
    }
  }

  // 4. Compute line items + capture WAC at sale time.
  const computedItems: ComputedSaleItem[] = [];
  const balanceCache = new Map<string, { qty: number; wac: bigint }>();
  for (const inp of body.items as SaleItemInput[]) {
    const product = productMap.get(inp.productId)!;
    const unitPriceMinor = inp.unitPrice ? toMinor(inp.unitPrice) : product.sellingPriceMinor;
    const discountMinor = inp.discount ? toMinor(inp.discount) : 0n;
    const lineTotal = BigInt(inp.quantity) * unitPriceMinor - discountMinor;
    if (lineTotal < 0n) {
      throw Errors.badRequest(
        `Line discount exceeds line total for ${product.sku}`,
        'INVALID_DISCOUNT',
      );
    }

    const cacheKey = `${inp.productId}|${branchId ?? ''}`;
    let bal = balanceCache.get(cacheKey);
    if (!bal) {
      const fetched = await getBalance(bizId, branchId, inp.productId, tx);
      bal = {
        qty: (fetched as any).quantity ?? 0,
        wac: (fetched as any).wacCostMinor ?? 0n,
      };
      balanceCache.set(cacheKey, bal);
    }

    if (!config.tenant.enableNegativeStock) {
      const alreadyConsumed = computedItems
        .filter((c) => c.productId === inp.productId)
        .reduce((acc, c) => acc + c.quantity, 0);
      if (bal.qty - alreadyConsumed < inp.quantity) {
        throw Errors.insufficientStock(
          `Insufficient stock for ${product.sku}: requested ${inp.quantity}, available ${bal.qty - alreadyConsumed}`,
        );
      }
    }

    const unitCostMinor = bal.wac;
    const totalCostMinor = BigInt(inp.quantity) * unitCostMinor;
    computedItems.push({
      productId: inp.productId,
      quantity: inp.quantity,
      unitPriceMinor,
      unitCostMinor,
      discountMinor,
      totalMinor: lineTotal,
      totalCostMinor,
    });
  }

  // 5. Compute totals.
  const totals = computeSaleTotals(computedItems, {
    cartDiscount: body.discount,
    taxRateBps: business.taxRateBps,
    payments: body.payments as SalePaymentInput[],
  });

  const receipt = receiptNo();
  const saleDate = body.saleDate ? new Date(body.saleDate) : new Date();

  // 6. Persist atomically.
  const sale = await tx.sale.create({
    data: {
      businessId: bizId,
      branchId,
      cashierId: userId,
      customerId: body.customerId ?? null,
      receiptNo: receipt,
      syncId: clientTxId,
      status: totals.status,
      subtotalMinor: totals.subtotalMinor,
      discountMinor: totals.discountMinor,
      taxMinor: totals.taxMinor,
      totalMinor: totals.totalMinor,
      amountPaidMinor: totals.amountPaidMinor,
      outstandingMinor: totals.outstandingMinor,
      notes: body.notes ?? null,
      saleDate,
    },
  });

  await tx.saleItem.createMany({
    data: computedItems.map((it) => ({
      saleId: sale.id,
      productId: it.productId,
      quantity: it.quantity,
      unitPriceMinor: it.unitPriceMinor,
      unitCostMinor: it.unitCostMinor,
      discountMinor: it.discountMinor,
      totalMinor: it.totalMinor,
      totalCostMinor: it.totalCostMinor,
    })),
  });

  if (body.payments.length > 0) {
    await tx.salePayment.createMany({
      data: body.payments.map((p) => ({
        saleId: sale.id,
        method: p.method,
        amountMinor: toMinor(p.amount),
        reference: p.reference ?? null,
      })),
    });
  }

  for (const it of computedItems) {
    await applyMovement(tx, {
      businessId: bizId,
      branchId,
      productId: it.productId,
      movementType: 'SALE_DEDUCTION',
      quantity: -Math.abs(it.quantity),
      unitCostMinor: it.unitCostMinor,
      referenceType: 'sale',
      referenceId: sale.id,
      reason: `Sale ${receipt}`,
      syncId: clientTxId,
      responsibleUserId: userId,
    });
  }

  if (totals.outstandingMinor > 0n && body.customerId) {
    await tx.customerCredit.create({
      data: {
        businessId: bizId,
        customerId: body.customerId,
        saleId: sale.id,
        amountMinor: totals.outstandingMinor,
        status: 'OPEN',
      },
    });
  }

  return { id: sale.id, receiptNo: receipt };
}

/**
 * Replay a stock-in. Mirrors POST /inventory/stock-in.
 */
async function replayStockIn(
  tx: Tx,
  bizId: string,
  userId: string,
  clientTxId: string,
  payload: Record<string, unknown>,
): Promise<{ id: string; movementId: string }> {
  const Schema = z
    .object({
      productId: z.string().uuid(),
      quantity: z.number().int().min(1).max(1_000_000_000),
      unitCost: moneyString.optional(),
      unitCostMinor: minorIntString.optional(),
      supplierId: z.string().uuid().optional().nullable(),
      purchaseReference: z.string().max(200).optional().nullable(),
      branchId: z.string().uuid().optional().nullable(),
      date: z.string().datetime().optional(),
      batchNo: z.string().max(200).optional().nullable(),
      expiryDate: z.string().datetime().optional().nullable(),
      notes: z.string().max(2000).optional().nullable(),
    })
    .refine((d) => !!d.unitCost || !!d.unitCostMinor, {
      message: 'Either unitCost or unitCostMinor is required',
      path: ['unitCost'],
    })
    .refine((d) => !(d.unitCost && d.unitCostMinor), {
      message: 'Provide either unitCost OR unitCostMinor, not both',
      path: ['unitCost'],
    });

  const parsed = Schema.safeParse(payload);
  if (!parsed.success) {
    throw Errors.badRequest(
      `Invalid stock_in payload: ${parsed.error.issues.map((i) => i.path.join('.') + ': ' + i.message).join('; ')}`,
      'SYNC_INVALID_PAYLOAD',
    );
  }
  const body = parsed.data;
  const branchId = body.branchId ?? null;
  const unitCostMinor = body.unitCostMinor ? BigInt(body.unitCostMinor) : toMinor(body.unitCost!);

  // Idempotency: check existing movement by syncId.
  const existingMovement = await tx.inventoryMovement.findFirst({
    where: { businessId: bizId, syncId: clientTxId },
    select: { id: true, referenceId: true },
  });
  if (existingMovement) {
    return { id: existingMovement.referenceId ?? existingMovement.id, movementId: existingMovement.id };
  }

  const product = await tx.product.findFirst({
    where: { id: body.productId, businessId: bizId },
    select: { id: true, name: true, sku: true },
  });
  if (!product) throw Errors.notFound('Product not found');

  const movementType: 'PURCHASE_RECEIPT' | 'INITIAL_STOCK' = body.purchaseReference
    ? 'PURCHASE_RECEIPT'
    : 'INITIAL_STOCK';

  const { movement, balance } = await applyMovement(tx, {
    businessId: bizId,
    branchId,
    productId: body.productId,
    movementType,
    quantity: body.quantity,
    unitCostMinor,
    referenceType: body.purchaseReference ? 'PURCHASE' : null,
    referenceId: null,
    batchNo: body.batchNo ?? null,
    expiryDate: body.expiryDate ? new Date(body.expiryDate) : null,
    reason: body.purchaseReference ? `Receipt: ${body.purchaseReference}` : 'Initial stock',
    notes: body.notes ?? null,
    syncId: clientTxId,
    responsibleUserId: userId,
  });

  if (body.batchNo || body.expiryDate) {
    await tx.stockBatch.create({
      data: {
        businessId: bizId,
        productId: body.productId,
        batchNo: body.batchNo ?? null,
        expiryDate: body.expiryDate ? new Date(body.expiryDate) : null,
        initialQty: body.quantity,
        remainingQty: body.quantity,
        unitCostMinor,
      },
    });
  }

  await tx.product.update({
    where: { id: body.productId },
    data: { costPriceMinor: balance.wacCostMinor },
  });

  return { id: movement.id, movementId: movement.id };
}

/**
 * Replay a stock-out. Mirrors POST /inventory/stock-out.
 */
async function replayStockOut(
  tx: Tx,
  bizId: string,
  userId: string,
  clientTxId: string,
  payload: Record<string, unknown>,
): Promise<{ id: string; movementId: string }> {
  const Schema = z.object({
    productId: z.string().uuid(),
    quantity: z.number().int().min(1).max(1_000_000_000),
    reason: StockOutReasonEnum,
    reference: z.string().max(200).optional().nullable(),
    branchId: z.string().uuid().optional().nullable(),
    date: z.string().datetime().optional(),
    notes: z.string().max(2000).optional().nullable(),
  });

  const parsed = Schema.safeParse(payload);
  if (!parsed.success) {
    throw Errors.badRequest(
      `Invalid stock_out payload: ${parsed.error.issues.map((i) => i.path.join('.') + ': ' + i.message).join('; ')}`,
      'SYNC_INVALID_PAYLOAD',
    );
  }
  const body = parsed.data;
  const branchId = body.branchId ?? null;

  // Idempotency: check existing movement by syncId.
  const existingMovement = await tx.inventoryMovement.findFirst({
    where: { businessId: bizId, syncId: clientTxId },
    select: { id: true },
  });
  if (existingMovement) {
    return { id: existingMovement.id, movementId: existingMovement.id };
  }

  const product = await tx.product.findFirst({
    where: { id: body.productId, businessId: bizId },
    select: { id: true, name: true, sku: true },
  });
  if (!product) throw Errors.notFound('Product not found');

  const movementType = reasonToMovementType(body.reason);
  const signedQty = -Math.abs(body.quantity);

  const { movement } = await applyMovement(tx, {
    businessId: bizId,
    branchId,
    productId: body.productId,
    movementType,
    quantity: signedQty,
    referenceType: body.reference ? 'MANUAL' : null,
    referenceId: null,
    reason: body.reason,
    notes: body.notes ?? null,
    syncId: clientTxId,
    responsibleUserId: userId,
  });

  if (movementType === 'SUPPLIER_RETURN') {
    const batch = await tx.stockBatch.findFirst({
      where: { businessId: bizId, productId: body.productId },
      orderBy: { receivedAt: 'desc' },
    });
    if (batch) {
      const newRemaining = Math.max(0, batch.remainingQty - body.quantity);
      await tx.stockBatch.update({
        where: { id: batch.id },
        data: { remainingQty: newRemaining },
      });
    }
  }

  return { id: movement.id, movementId: movement.id };
}

