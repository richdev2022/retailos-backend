// GET /sync/pull
// =====================================================
const SyncPullQuerySchema = z.object({
  lastSyncAt: z.string().datetime().optional(),
  types: z
    .string()
    .optional()
    .transform((v) =>
      v
        ? v
            .split(',')
            .map((s) => s.trim().toLowerCase())
            .filter(Boolean)
        : null,
    ),
});

syncRouter.get(
  '/pull',
  requirePermission('sale:view'), // anyone who can read business data can pull
  validateQuery(SyncPullQuerySchema),
  asyncHandler(async (req: Request, res: Response) => {
    const bizId = req.activeBusinessId!;
    const q = req.query as unknown as z.infer<typeof SyncPullQuerySchema>;

    // Use the client's cursor if provided; otherwise return everything.
    const cursor = q.lastSyncAt ? new Date(q.lastSyncAt) : new Date(0);
    const serverTimestamp = new Date();

    const requested = q.types ?? ['products', 'sales', 'inventory', 'customers', 'suppliers', 'expenses'];
    const wants = (t: string) => requested.includes(t);

    // Run the queries in parallel.
    const [products, sales, inventoryBalances, customers, suppliers, expenses] =
      await Promise.all([
        wants('products')
          ? prisma.product.findMany({
              where: { businessId: bizId, updatedAt: { gt: cursor } },
              orderBy: { updatedAt: 'asc' },
            })
          : Promise.resolve([]),
        wants('sales')
          ? prisma.sale.findMany({
              where: { businessId: bizId, updatedAt: { gt: cursor } },
              orderBy: { updatedAt: 'asc' },
            })
          : Promise.resolve([]),
        wants('inventory')
          ? prisma.inventoryBalance.findMany({
              where: { businessId: bizId, updatedAt: { gt: cursor } },
              orderBy: { updatedAt: 'asc' },
            })
          : Promise.resolve([]),
        wants('customers')
          ? prisma.customer.findMany({
              where: { businessId: bizId, updatedAt: { gt: cursor } },
              orderBy: { updatedAt: 'asc' },
            })
          : Promise.resolve([]),
        wants('suppliers')
          ? prisma.supplier.findMany({
              where: { businessId: bizId, updatedAt: { gt: cursor } },
              orderBy: { updatedAt: 'asc' },
            })
          : Promise.resolve([]),
        wants('expenses')
          ? prisma.expense.findMany({
              where: { businessId: bizId, updatedAt: { gt: cursor } },
              orderBy: { updatedAt: 'asc' },
            })
          : Promise.resolve([]),
      ]);

    // Serialise BigInt fields to strings for every collection.
    const changes = {
      products: products.map((p: any) => ({
        ...p,
        costPriceMinor: p.costPriceMinor?.toString() ?? '0',
        sellingPriceMinor: p.sellingPriceMinor?.toString() ?? '0',
        wholesalePriceMinor: p.wholesalePriceMinor?.toString() ?? null,
        deletedAt: p.archivedAt ?? null, // soft-delete via archive
      })),
      sales: sales.map((s: any) => ({
        ...s,
        subtotalMinor: s.subtotalMinor?.toString() ?? '0',
        discountMinor: s.discountMinor?.toString() ?? '0',
        taxMinor: s.taxMinor?.toString() ?? '0',
        totalMinor: s.totalMinor?.toString() ?? '0',
        amountPaidMinor: s.amountPaidMinor?.toString() ?? '0',
        outstandingMinor: s.outstandingMinor?.toString() ?? '0',
        deletedAt: s.cancelledAt ?? null, // soft-delete via cancellation
      })),
      inventory_balances: inventoryBalances.map((b: any) => ({
        ...b,
        wacCostMinor: b.wacCostMinor?.toString() ?? '0',
        deletedAt: null,
      })),
      customers: customers.map((c: any) => ({ ...c, deletedAt: null })),
      suppliers: suppliers.map((s: any) => ({ ...s, deletedAt: null })),
      expenses: expenses.map((e: any) => ({
        ...e,
        amountMinor: e.amountMinor?.toString() ?? '0',
        deletedAt: null, // Expense is hard-deleted; no soft-delete field
      })),
    };

    writeAudit(req, {
      action: 'sync.pull',
      resourceType: 'sync_event',
      resourceId: bizId,
      change: {
        cursor: cursor.toISOString(),
        types: requested,
        counts: {
          products: changes.products.length,
          sales: changes.sales.length,
          inventory_balances: changes.inventory_balances.length,
          customers: changes.customers.length,
          suppliers: changes.suppliers.length,
          expenses: changes.expenses.length,
        },
      },
    });

    return sendSuccess(
      res,
      {
        lastSyncAt: serverTimestamp.toISOString(),
        changes,
      },
      'OK',
    );
  }),
);

