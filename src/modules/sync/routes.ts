// GET /sync/status
// =====================================================
syncRouter.get(
  '/status',
  requirePermission('sale:view'),
  asyncHandler(async (req: Request, res: Response) => {
    const bizId = req.activeBusinessId!;

    // Group counts by status.
    const grouped = await prisma.syncEvent.groupBy({
      by: ['status'],
      _count: { _all: true },
      where: { businessId: bizId },
    });

    const counts: Record<string, number> = {
      QUEUED: 0,
      PROCESSED: 0,
      REJECTED: 0,
      CONFLICT: 0,
    };
    for (const g of grouped) {
      counts[g.status] = g._count._all;
    }

    // Last successful sync = max(processedAt) across PROCESSED events.
    const lastProcessed = await prisma.syncEvent.findFirst({
      where: { businessId: bizId, status: 'PROCESSED' },
      orderBy: { processedAt: 'desc' },
      select: { processedAt: true, clientTxId: true, operation: true },
    });

    return sendSuccess(
      res,
      {
        counts,
        pending: counts.QUEUED,
        processed: counts.PROCESSED,
        rejected: counts.REJECTED,
        conflict: counts.CONFLICT,
        lastSuccessfulSyncAt: lastProcessed?.processedAt ?? null,
        lastSuccessfulSync: lastProcessed
          ? {
              clientTxId: lastProcessed.clientTxId,
              operation: lastProcessed.operation,
              processedAt: lastProcessed.processedAt,
            }
          : null,
      },
      'OK',
    );
  }),
);
