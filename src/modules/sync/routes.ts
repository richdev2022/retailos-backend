const SyncOperationEnum = z.enum([
  'sale',
  'stock_in',
  'stock_out',
  'adjustment',
  'expense',
]);
type SyncOperationCode = z.infer<typeof SyncOperationEnum>;

const SyncStatusEnum = z.enum(['QUEUED', 'PROCESSED', 'REJECTED', 'CONFLICT']);

const moneyInput = z.union([
  z
    .string()
    .regex(/^\d+(\.\d{1,2})?$/, 'Must be a decimal string like "1250.50"'),
  z.number().nonnegative().finite(),
]);
const moneyString = moneyInput.transform((v: string | number) => String(v));

const minorIntString = z
  .string()
  .regex(/^\d+$/, 'Must be a non-negative integer string of minor units');

const PaymentMethodEnum = z.enum([
  'CASH',
  'BANK_TRANSFER',
  'CARD_POS',
  'CUSTOMER_CREDIT',
  'OTHER',
]);

const StockOutReasonEnum = z.enum([
  'DAMAGED',
  'EXPIRED',
  'INTERNAL_USE',
  'THEFT_MISSING',
  'SUPPLIER_RETURN',
  'OTHER',
]);

interface SyncOperationInput {
  clientTxId: string;
  operation: SyncOperationCode;
  payload: Record<string, unknown>;
  createdAt: string;
}

interface SyncPushResultItem {
  clientTxId: string;
  status: 'PROCESSED' | 'REJECTED' | 'QUEUED';
  result?: { id: string; [key: string]: unknown } | null;
  error?: string | null;
}

/** Fire-and-forget audit log write. Never throws. */
function writeAudit(
  req: Request,
  opts: { action: string; resourceType: string; resourceId: string; change?: unknown },
) {
  const businessId = req.activeBusinessId;
  if (!businessId) return;
  prisma.auditLog
    .create({
      data: {
        businessId,
        actorId: req.user?.id ?? null,
        adminActorId: req.user?.scope === 'admin' ? req.user.id : null,
        action: opts.action,
        resourceType: opts.resourceType,
        resourceId: opts.resourceId,
        change: (opts.change as any) ?? null,
        ipAddress: req.ip ?? null,
        userAgent: req.headers['user-agent'] ?? null,
      },
    })
    .catch(() => {
      /* fire and forget — never throw from audit */
    });
}

/** Resolve the effective branchId: payload first, then the request's active branch. */
function resolveBranchId(
  payloadBranchId: string | null | undefined,
  req: Request,
): string | null {
  if (payloadBranchId) return payloadBranchId;
  return req.activeBranchId ?? null;
}

/** Extract a usable error message from a thrown value. */
function errorMessage(err: unknown): string {
  if (err instanceof Error) return err.message;
  if (typeof err === 'string') return err;
  try {
    return JSON.stringify(err);
  } catch {
    return 'Unknown error';
  }
}

/** Map stock-out reason to MovementType. Mirrors inventory/routes.ts. */
function reasonToMovementType(reason: z.infer<typeof StockOutReasonEnum>) {
  switch (reason) {
    case 'DAMAGED':
      return 'DAMAGED' as const;
    case 'EXPIRED':
      return 'EXPIRED' as const;
    case 'SUPPLIER_RETURN':
      return 'SUPPLIER_RETURN' as const;
    case 'INTERNAL_USE':
    case 'THEFT_MISSING':
    case 'OTHER':
    default:
      return 'STOCK_OUT' as const;
  }
}

